static int __attribute__((unused)) hevc_annexb_append(uint8_t *out, size_t cap, size_t *n, const uint8_t *nal, size_t nn)
{
    if (*n + 4 + nn > cap) {
        return -1;
    }
    out[(*n)++] = 0;
    out[(*n)++] = 0;
    out[(*n)++] = 0;
    out[(*n)++] = 1;
    memcpy(out + *n, nal, nn);
    *n += nn;
    return 0;
}

static int __attribute__((unused)) hevc_annexb_csd(uint8_t *out, size_t cap, size_t *n,
                           const uint8_t *vps, size_t nv,
                           const uint8_t *sps, size_t ns,
                           const uint8_t *pps, size_t np)
{
    *n = 0;
    if (hevc_annexb_append(out, cap, n, vps, nv) != 0 ||
        hevc_annexb_append(out, cap, n, sps, ns) != 0 ||
        hevc_annexb_append(out, cap, n, pps, np) != 0) {
        return -1;
    }
    return 0;
}

static int __attribute__((unused)) hevc_key_au(uint8_t *out, size_t cap, size_t *n,
                       const uint8_t *vps, size_t nv,
                       const uint8_t *sps, size_t ns,
                       const uint8_t *pps, size_t np,
                       const uint8_t *irap, size_t ni)
{
    if (hevc_annexb_csd(out, cap, n, vps, nv, sps, ns, pps, np) != 0) {
        return -1;
    }
    return hevc_annexb_append(out, cap, n, irap, ni);
}

