"""Generate src/obf/obf_strings.h — 改 STRINGS 后重跑。

真源在本文件明文；so 里只剩密文。算法同超级直播 rolling XOR；
密钥在 src/obf/obfdec.c（MsMedia SDK 独有，勿与直播包共用）。
"""
